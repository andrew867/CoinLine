using System.Security.Cryptography;
using System.Text.Json;
using HostPlatform.Firmware;
using HostPlatform.Transport;

namespace HostPlatform.Tests.Unit;

public sealed class DlaAuthorizedCodeServerSessionTests
{
    private static readonly ModemPacingProfile Pacing = new() { InterBlockDelayMs = 0, RetrySpacingMs = 0, AfterControlByteDelayMs = 0 };
    private static readonly DlaAuthorizedSessionOptions Options = new(TimeSpan.FromSeconds(15), TimeSpan.FromSeconds(3), TimeSpan.FromSeconds(3),
        DlaResponseMode.Required, 1000, 3);

    [Fact]
    public async Task Exact_grant_is_checked_and_request_memory_is_cleared_before_delivery()
    {
        byte[] image = Enumerable.Range(0, 4 * 4096).Select(index => (byte)(index % 251)).ToArray();
        byte[] request = Request(1, 2);
        // Independent generated bytes stand in for the protected request fields.
        request[23] = 0x42; request[24] = 0x73;
        var (server, terminal) = MemoryDuplexPair.CreateUnbounded(); await using var serverDispose = server; await using var terminalDispose = terminal;
        ReadOnlyMemory<byte> observed = default; int calls = 0;
        var serve = DlaAuthorizedCodeServerSession.RunAsync(server, (raw, _) =>
        {
            calls++; Assert.Equal(request, raw.ToArray()); observed = raw;
            return ValueTask.FromResult<DlaAuthorizedPayload?>(new(image, Convert.ToHexString(SHA256.HashData(image)), [2]));
        }, Options);
        await Send(terminal, request);
        var received = await DlaXmodemReceiver.ReceiveAsync(terminal, 1000, 3, 8192, null, CancellationToken.None);
        Assert.Equal(image.AsSpan(2 * 4096, 4096).ToArray(), received.Data.AsSpan(10, 4096).ToArray());
        await Send(terminal, [DlaCodeServerSession.ResponseDownload]);
        var result = await serve;
        Assert.Equal(1, calls); Assert.True(result.RequestReceived && result.AuthorizationMatched && result.TransportCompleted && result.ApplicationResponseSeen && result.Success);
        Assert.Equal(new byte[] { 2 }, result.DeliveredBlocks); Assert.Equal(5, result.PacketsSent); Assert.Equal(1, result.RequestedBlockCount);
        Assert.Equal(69, observed.Length); Assert.All(observed.ToArray(), value => Assert.Equal(0, value));
        Assert.DoesNotContain("sha256", JsonSerializer.Serialize(result), StringComparison.OrdinalIgnoreCase);
    }

    [Theory]
    [InlineData("denied", true)]
    [InlineData("wrong-blocks", true)]
    [InlineData("wrong-digest", true)]
    [InlineData("unsupported-reason", false)]
    [InlineData("empty-selection", false)]
    public async Task Rejected_request_or_grant_never_sends_application_data(string scenario, bool expectedCallback)
    {
        var image = new byte[4 * 4096]; var request = scenario == "empty-selection" ? Request(1) : Request(scenario == "unsupported-reason" ? (byte)4 : (byte)1, 2);
        var (server, terminal) = MemoryDuplexPair.CreateUnbounded(); await using var serverDispose = server; await using var terminalDispose = terminal;
        int calls = 0; ReadOnlyMemory<byte> observed = default;
        var serve = DlaAuthorizedCodeServerSession.RunAsync(server, (raw, _) =>
        {
            calls++; observed = raw;
            return ValueTask.FromResult<DlaAuthorizedPayload?>(scenario == "denied" ? null : new(image,
                scenario == "wrong-digest" ? new string('0', 64) : Convert.ToHexString(SHA256.HashData(image)), scenario == "wrong-blocks" ? [1] : [2]));
        }, Options);
        await Send(terminal, request);
        var result = await serve;
        Assert.Equal(expectedCallback ? 1 : 0, calls); Assert.True(result.RequestReceived);
        Assert.False(result.AuthorizationMatched || result.TransportCompleted || result.Success); Assert.Empty(result.DeliveredBlocks); Assert.Equal(0, result.PacketsSent);
        Assert.All(observed.ToArray(), value => Assert.Equal(0, value));
        using var wait = new CancellationTokenSource(TimeSpan.FromMilliseconds(50));
        await Assert.ThrowsAnyAsync<OperationCanceledException>(async () => { await terminal.ReadAsync(new byte[1], wait.Token); });
    }

    [Fact]
    public async Task Bounded_request_without_sender_never_reaches_authorization()
    {
        var (server, terminal) = MemoryDuplexPair.CreateUnbounded(); await using var serverDispose = server; await using var terminalDispose = terminal;
        var result = await DlaAuthorizedCodeServerSession.RunAsync(server, (_, _) => throw new InvalidOperationException("Unexpected authorization"),
            Options with { SessionTimeout = TimeSpan.FromSeconds(1), RequestTimeout = TimeSpan.FromMilliseconds(30), AckTimeoutMs = 100 });
        Assert.False(result.RequestReceived || result.AuthorizationMatched || result.TransportCompleted || result.Success);
        Assert.Empty(result.DeliveredBlocks);
    }

    [Fact]
    public async Task Required_response_is_separate_from_completed_transport()
    {
        var image = new byte[2 * 4096]; var request = Request(2, 1);
        var (server, terminal) = MemoryDuplexPair.CreateUnbounded(); await using var serverDispose = server; await using var terminalDispose = terminal;
        var serve = DlaAuthorizedCodeServerSession.RunAsync(server, (_, _) => ValueTask.FromResult<DlaAuthorizedPayload?>(
            new(image, Convert.ToHexString(SHA256.HashData(image)), [1])), Options with { ResponseTimeout = TimeSpan.FromMilliseconds(50) });
        await Send(terminal, request);
        var received = await DlaXmodemReceiver.ReceiveAsync(terminal, 1000, 3, 8192, null, CancellationToken.None);
        Assert.Equal(1, received.Data[1]);
        var result = await serve;
        Assert.True(result.AuthorizationMatched && result.TransportCompleted); Assert.False(result.ApplicationResponseSeen || result.Success);
        Assert.Equal(new byte[] { 1 }, result.DeliveredBlocks);
    }

    private static byte[] Request(byte reason, params byte[] blocks)
    {
        var request = new byte[69]; request[1] = reason;
        foreach (var block in blocks) request[37 + (block >> 3)] |= (byte)(1 << (block & 7));
        return request;
    }

    private static async Task Send(IAsyncDuplexTransport peer, byte[] bytes)
    {
        var result = await XmodemSender.SendAsync(peer, bytes, Pacing, 1000, 3, TimeSpan.FromSeconds(3), null, null, null, CancellationToken.None);
        Assert.True(result.Success, result.Detail);
    }
}
